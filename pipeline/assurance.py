"""Executed assurance for a coding bundle: the controls, and a reproducible export.

`controls` is the executed validity suite (`author.controls.run`). `generated_
problems` proves the package on disk is exactly what its spec generates: the
spec is rebuilt into scratch over a copy of the same fixture and every file
under `artifacts.ROOTS` is compared byte for byte. A package that cannot be
reproduced from its spec is one whose provenance has already drifted, and
Harbor's preflight refuses to run it.
"""
from __future__ import annotations

import hashlib
import shutil
import tempfile
from pathlib import Path

from .artifacts import ROOTS
from .author import build as build_mod
from .author.contracts import contained, strict_json


def controls(bundle: Path) -> dict:
    from .author import controls as controls_mod
    return controls_mod.run(Path(bundle))


def _files(root: Path) -> dict[str, str]:
    root = Path(root).resolve()
    out = {}
    for rel in ROOTS:
        base = contained(root, rel)
        candidates = sorted(base.rglob("*")) if base.is_dir() else [base]
        for path in candidates:
            if not path.is_file() or "__pycache__" in path.parts:
                continue
            key = path.relative_to(root).as_posix()
            if key.startswith("environment/repo/"):
                continue
            out[key] = hashlib.sha256(path.read_bytes()).hexdigest()
    return out


def generated_problems(bundle: Path) -> list[str]:
    """Rebuild from authoring/spec.json in scratch; any byte that differs is a problem."""
    bundle = Path(bundle)
    try:
        spec = strict_json((bundle / "authoring/spec.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return [f"authoring/spec.json is unreadable: {exc}"]
    with tempfile.TemporaryDirectory(prefix="arena-regen-") as temp:
        scratch = Path(temp) / bundle.name
        (scratch / "environment").mkdir(parents=True)
        shutil.copytree(bundle / "environment/repo", scratch / "environment/repo")
        # The ledger and any privacy manifests are written by later stages, not
        # by the build; copy them so the comparison covers the build alone.
        if (bundle / "provenance").is_dir():
            shutil.copytree(bundle / "provenance", scratch / "provenance")
        # The designer's declaration of authored fixture bytes is an input the
        # ledger is rebuilt from, not a product of the spec: it is a release
        # surface (artifacts.ROOTS) and travels with the package unchanged.
        declared = bundle / "authoring/extraction/fixture-authored.json"
        if declared.is_file():
            (scratch / "authoring/extraction").mkdir(parents=True, exist_ok=True)
            shutil.copyfile(declared, scratch / "authoring/extraction/fixture-authored.json")
        # Independent-oracle derivations are evidence the designer's tool wrote
        # (artifacts.ROOTS), checked by oracle.problems and never built from the
        # spec. Counting them as drift blocked c-001-design-data-validator
        # (envs-s2, 2026-10-03) after its controls and review had passed.
        if (bundle / "authoring/oracles").is_dir():
            shutil.copytree(bundle / "authoring/oracles", scratch / "authoring/oracles")
        try:
            build_mod.build(spec, scratch)
        except Exception as exc:  # noqa: BLE001
            return [f"the spec no longer builds: {type(exc).__name__}: {exc}"]
        # The package name is rewritten by naming.apply after the build; carry it.
        from . import naming
        try:
            import tomllib
            level = strict_json((bundle / "provenance/ledger.json").read_text()).get("faithfulness_level") \
                if (bundle / "provenance/ledger.json").is_file() else None
            if level:
                naming.apply(scratch, level)
            want = tomllib.loads((bundle / "task.toml").read_text())["task"]["name"]
            got = tomllib.loads((scratch / "task.toml").read_text())["task"]["name"]
            if want != got:
                (scratch / "task.toml").write_text(naming.rename_text((scratch / "task.toml").read_text(), want))
        except (OSError, ValueError, KeyError):
            pass
        expected = _files(scratch)
    actual = _files(bundle)
    problems = []
    for key in sorted(set(expected) | set(actual)):
        if key not in actual:
            problems.append(f"{key}: generated by the spec but absent from the package")
        elif key not in expected:
            problems.append(f"{key}: present in the package but not generated by the spec")
        elif expected[key] != actual[key]:
            problems.append(f"{key}: differs from what the spec generates")
    return problems
